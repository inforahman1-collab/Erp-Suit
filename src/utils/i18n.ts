export function formatCurrency(amount: number, currencyCode: string = 'BDT', symbol?: string): string {
  const isNegative = amount < 0;
  const absAmount = Math.abs(amount);
  const sym = symbol || (currencyCode === 'BDT' ? '৳' : currencyCode === 'USD' ? '$' : currencyCode === 'EUR' ? '€' : currencyCode === 'GBP' ? '£' : currencyCode === 'SAR' ? '﷼' : currencyCode === 'AED' ? 'د.إ' : currencyCode === 'INR' ? '₹' : currencyCode);
  const formatted = absAmount.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  return `${isNegative ? '-' : ''}${sym} ${formatted}`;
}

export function formatBDT(amount: number): string {
  const isNegative = amount < 0;
  const absAmount = Math.abs(amount);
  const fixed = absAmount.toFixed(2);
  const [integerPart, decimalPart] = fixed.split('.');

  // South Asian comma numbering system (e.g., 12,34,567.89)
  let lastThree = integerPart.substring(integerPart.length - 3);
  const otherNumbers = integerPart.substring(0, integerPart.length - 3);
  if (otherNumbers !== '') {
    lastThree = ',' + lastThree;
  }
  const formattedInteger = otherNumbers.replace(/\B(?=(\d{2})+(?!\d))/g, ',') + lastThree;

  return `${isNegative ? '-' : ''}৳ ${formattedInteger}.${decimalPart}`;
}

export function formatDateBD(dateString: string): string {
  try {
    const d = new Date(dateString);
    if (isNaN(d.getTime())) return dateString;
    const day = String(d.getDate()).padStart(2, '0');
    const month = String(d.getMonth() + 1).padStart(2, '0');
    const year = d.getFullYear();
    return `${day}/${month}/${year}`;
  } catch {
    return dateString;
  }
}
